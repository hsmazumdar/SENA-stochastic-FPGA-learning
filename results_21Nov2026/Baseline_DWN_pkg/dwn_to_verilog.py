"""
dwn_to_verilog.py - emit synthesizable Verilog for a trained DWN (model.json
from train_dwn.py) plus test vectors and a bit-exact self-checking testbench.

This is OUR re-implementation of the published DWN inference structure
(Bacellar et al., ICML 2024, Fig. 3: LUT-n nodes -> registered -> popcount per
class -> argmax).  The DWN authors did not release an RTL generator.

Datapath (fully parallel, 1 inference/clock, pipelined):
    x[783:0] --(opt. input reg)--> LUT layer 1 --reg--> LUT layer 2 --reg-->
    per-class popcount (balanced adder tree) --reg--> argmax (balanced
    comparator tree, ties -> lowest class index = torch/numpy argmax) --reg-->
    pred[3:0], counts
LUT node j of a layer:  out = T_j[{x[m_{n-1}], ..., x[m_1], x[m_0]}]
(address bit l = input mapping[j][l], exactly as efd_cuda_kernel.cu).

Usage
    python dwn_to_verilog.py runs/sm/seed0/model.json --out quartus/gen
    python dwn_to_verilog.py <model.json> --out <dir> --sim   # + run Icarus check
Outputs in --out
    dwn_core.v  dwn_params.vh  dwn_core_info.json
    test_x.hex (one 784-bit vector/line, bit i = pixel i)  test_exp.hex ({label,pred})
    test_counts.hex (class popcounts, class c at [c*CW +: CW])  tb_dwn_core.v
"""
from __future__ import annotations

import argparse
import json
import math
import os
import shutil
import subprocess
import sys

import numpy as np

import dwn_ref


class Emitter:
    def __init__(self):
        self.lines = []
        self.uid = 0

    def w(self, s=""):
        self.lines.append(s)

    def tmp(self, p):
        self.uid += 1
        return f"{p}{self.uid}"


def adder_tree(em, terms, prefix):
    """terms: list of (expr, width). Returns (signal, width) of the sum."""
    if not terms:
        return "1'b0", 1
    level = list(terms)
    while len(level) > 1:
        nxt = []
        for i in range(0, len(level) - 1, 2):
            (a, wa), (b, wb) = level[i], level[i + 1]
            wo = max(wa, wb) + 1
            s = em.tmp(prefix)
            em.w(f"    wire [{wo-1}:0] {s} = {a} + {b};")
            nxt.append((s, wo))
        if len(level) % 2:
            nxt.append(level[-1])
        level = nxt
    return level[0]


def argmax_tree(em, leaves, cw, iw):
    """leaves: list of (count_expr, idx_int). Ties -> lower index."""
    level = [(c, f"{iw}'d{i}") for c, i in leaves]
    while len(level) > 1:
        nxt = []
        for i in range(0, len(level) - 1, 2):
            (ca, ia), (cb, ib) = level[i], level[i + 1]
            sel = em.tmp("am_s")
            c, ix = em.tmp("am_c"), em.tmp("am_i")
            em.w(f"    wire {sel} = ({cb} > {ca});   // strict: tie keeps lower index")
            em.w(f"    wire [{cw-1}:0] {c} = {sel} ? {cb} : {ca};")
            em.w(f"    wire [{iw-1}:0] {ix} = {sel} ? {ib} : {ia};")
            nxt.append((c, ix))
        if len(level) % 2:
            nxt.append(level[-1])
        level = nxt
    return level[0]


def emit_core(model, reg_input=True, reg_pop=True, reg_argmax=True):
    em = Emitter()
    n_in, K = model["n_in"], model["n_classes"]
    last = model["layers"][-1]["n_out"]
    G, sl = dwn_ref.group_slices(last, K)
    CW = max(1, math.ceil(math.log2(G + 1)))
    IW = max(1, math.ceil(math.log2(K)))
    lat = int(reg_input) + len(model["layers"]) + int(reg_pop) + int(reg_argmax)
    sha = model.get("model_sha256", dwn_ref.model_sha256(model))

    em.w("// " + "=" * 76)
    em.w("// dwn_core.v - AUTO-GENERATED by dwn_to_verilog.py (SENA V13 DWN baseline)")
    em.w("// Re-implementation of the DWN inference structure (Bacellar et al., ICML 2024).")
    em.w(f"// model_sha256 {sha}")
    em.w(f"// layers {[l['n_out'] for l in model['layers']]}  n={[l['n'] for l in model['layers']]}"
         f"  classes {K}  group size {G}  count width {CW}  latency {lat} clk")
    em.w("// 1 inference per clock (fully pipelined). Ties in argmax -> lowest class.")
    em.w("// " + "=" * 76)
    em.w("`timescale 1ns/1ps")
    em.w("module dwn_core (")
    em.w("    input  wire              clk,")
    em.w("    input  wire              rst_n,")
    em.w("    input  wire              in_valid,")
    em.w(f"    input  wire [{n_in-1}:0]    x,")
    em.w("    output wire              out_valid,")
    em.w(f"    output wire [{IW-1}:0]        pred,")
    em.w(f"    output wire [{K*CW-1}:0]      counts")
    em.w(");")
    em.w(f"    localparam integer LATENCY = {lat};")
    em.w(f"    reg [LATENCY-1:0] vpipe;")
    em.w("    always @(posedge clk or negedge rst_n)")
    em.w("        if (!rst_n) vpipe <= {LATENCY{1'b0}};")
    if lat == 1:
        em.w("        else vpipe <= in_valid;")
    else:
        em.w("        else vpipe <= {vpipe[LATENCY-2:0], in_valid};")
    em.w("    assign out_valid = vpipe[LATENCY-1];")
    em.w()
    if reg_input:
        em.w(f"    reg [{n_in-1}:0] s0;")
        em.w("    always @(posedge clk) s0 <= x;")
        src = "s0"
    else:
        src = "x"
    for li, L in enumerate(model["layers"], 1):
        n, N = L["n"], L["n_out"]
        em.w(f"    // ---- LUT layer {li}: {N} x LUT-{n} ----")
        em.w(f"    wire [{N-1}:0] l{li}_c;")
        em.w(f"    reg  [{N-1}:0] l{li}_r;")
        for j, (m, h) in enumerate(zip(L["mapping"], L["luts_hex"])):
            addr = ", ".join(f"{src}[{m[l]}]" for l in reversed(range(n)))
            em.w(f"    localparam [{2**n-1}:0] T{li}_{j} = {2**n}'h{h};")
            em.w(f"    assign l{li}_c[{j}] = T{li}_{j}[{{{addr}}}];")
        em.w(f"    always @(posedge clk) l{li}_r <= l{li}_c;")
        src = f"l{li}_r"
    em.w()
    em.w(f"    // ---- GroupSum popcounts: {K} groups of {G} ----")
    cnt_sig = []
    for c, (a, b) in enumerate(sl):
        terms = [(f"{src}[{i}]", 1) for i in range(a, b)] or [("1'b0", 1)]
        s, wdt = adder_tree(em, terms, f"pc{c}_")
        cc = f"cnt{c}_c"
        rhs = f"{s}[{CW-1}:0]" if (wdt > CW and not s.startswith("1'")) else s
        em.w(f"    wire [{CW-1}:0] {cc} = {rhs};   // max {b - a} fits {CW} bits")
        cnt_sig.append(cc)
    if reg_pop:
        regs = []
        for c, cc in enumerate(cnt_sig):
            em.w(f"    reg [{CW-1}:0] cnt{c}_r;")
            em.w(f"    always @(posedge clk) cnt{c}_r <= {cc};")
            regs.append(f"cnt{c}_r")
        cnt_sig = regs
    em.w()
    em.w("    // ---- argmax (balanced tree) ----")
    best_c, best_i = argmax_tree(em, [(s, i) for i, s in enumerate(cnt_sig)], CW, IW)
    packed = "{" + ", ".join(reversed(cnt_sig)) + "}"
    if reg_argmax:
        em.w(f"    reg [{IW-1}:0] pred_r;")
        em.w(f"    reg [{K*CW-1}:0] counts_r;")
        em.w(f"    always @(posedge clk) begin pred_r <= {best_i}; counts_r <= {packed}; end")
        em.w("    assign pred = pred_r;")
        em.w("    assign counts = counts_r;")
    else:
        em.w(f"    assign pred = {best_i};")
        em.w(f"    assign counts = {packed};")
    em.w("endmodule")
    info = {"latency_cycles": lat, "count_width": CW, "group_size": G, "pred_width": IW,
            "n_in": n_in, "n_classes": K, "reg_input": reg_input, "reg_pop": reg_pop,
            "reg_argmax": reg_argmax,
            "lut_nodes_per_layer": [l["n_out"] for l in model["layers"]],
            "lut_inputs_per_layer": [l["n"] for l in model["layers"]],
            "total_lut_nodes": sum(l["n_out"] for l in model["layers"]),
            "distinct_inputs_used_layer1": len(set(v for m in model["layers"][0]["mapping"] for v in m)),
            "model_sha256": sha, "model_meta": model.get("meta", {})}
    return "\n".join(em.lines) + "\n", info


TB = r"""// tb_dwn_core.v - AUTO-GENERATED bit-exact check: RTL vs Python integer model
`timescale 1ns/1ps
module tb_dwn_core;
    `include "dwn_params.vh"
    reg clk = 0, rst_n = 0, in_valid = 0;
    reg  [DWN_N_IN-1:0] x;
    wire out_valid;
    wire [DWN_IW-1:0] pred;
    wire [DWN_K*DWN_CW-1:0] counts;
    reg [DWN_N_IN-1:0]      xm [0:DWN_N_TEST-1];
    reg [7:0]               em [0:DWN_N_TEST-1];
    reg [DWN_K*DWN_CW-1:0]  cm [0:DWN_N_TEST-1];
    integer i, k, pm, cmis, correct, t_first_in, t_first_out, cyc;
    dwn_core dut (.clk(clk), .rst_n(rst_n), .in_valid(in_valid), .x(x),
                  .out_valid(out_valid), .pred(pred), .counts(counts));
    always #5 clk = ~clk;
    always @(posedge clk) cyc <= cyc + 1;
    initial begin
        $readmemh("test_x.hex", xm);
        $readmemh("test_exp.hex", em);
        $readmemh("test_counts.hex", cm);
        cyc = 0; k = 0; pm = 0; cmis = 0; correct = 0; t_first_in = -1; t_first_out = -1;
        x = 0;
        repeat (3) @(posedge clk);
        rst_n = 1;
        @(posedge clk);
        for (i = 0; i < DWN_N_TEST; i = i + 1) begin
            @(negedge clk); in_valid = 1; x = xm[i];
            if (t_first_in < 0) t_first_in = cyc;
        end
        @(negedge clk); in_valid = 0;
        wait (k == DWN_N_TEST);
        $display("RESULT n=%0d pred_mismatch=%0d count_mismatch=%0d rtl_correct=%0d latency=%0d expected_latency=%0d",
                 DWN_N_TEST, pm, cmis, correct, t_first_out - t_first_in, DWN_LATENCY);
        if (pm == 0 && cmis == 0 && (t_first_out - t_first_in) == DWN_LATENCY)
            $display("BIT-EXACT PASS");
        else
            $display("BIT-EXACT FAIL");
        $finish;
    end
    always @(posedge clk) if (out_valid) begin
        if (t_first_out < 0) t_first_out = cyc;
        if (pred !== em[k][3:0]) pm = pm + 1;
        if (counts !== cm[k]) cmis = cmis + 1;
        if (pred == em[k][7:4]) correct = correct + 1;
        k = k + 1;
    end
endmodule
"""


def write_vectors(out, model, X, y, n_test):
    X, y = X[:n_test], y[:n_test]
    pred, counts = dwn_ref.infer_int(model, X)
    G, _ = dwn_ref.group_slices(model["layers"][-1]["n_out"], model["n_classes"])
    CW = max(1, math.ceil(math.log2(G + 1)))
    nd = (X.shape[1] + 3) // 4
    with open(os.path.join(out, "test_x.hex"), "w") as f:
        for row in X:
            v = 0
            for i in np.flatnonzero(row):
                v |= 1 << int(i)
            f.write(format(v, f"0{nd}x") + "\n")
    with open(os.path.join(out, "test_exp.hex"), "w") as f:
        for lab, p in zip(y, pred):
            f.write(format((int(lab) << 4) | int(p), "02x") + "\n")
    with open(os.path.join(out, "test_counts.hex"), "w") as f:
        for row in counts:
            v = 0
            for c, cnt in enumerate(row):
                v |= int(cnt) << (c * CW)
            f.write(format(v, f"0{(len(row)*CW+3)//4}x") + "\n")
    return pred, counts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("model")
    ap.add_argument("--data", default="data/mnist_bin_t0.3_tr10000_te2500_s2026.npz")
    ap.add_argument("--out", default="quartus/gen")
    ap.add_argument("--n-test", type=int, default=2500, help="vectors for TB and board ROM")
    ap.add_argument("--no-reg-input", action="store_true")
    ap.add_argument("--no-reg-pop", action="store_true")
    ap.add_argument("--no-reg-argmax", action="store_true")
    ap.add_argument("--sim", action="store_true", help="run Icarus Verilog bit-exact check")
    ap.add_argument("--iverilog", default="iverilog")
    ap.add_argument("--vvp", default="vvp")
    ap.add_argument("--force", action="store_true", help="allow writing into a non-empty --out")
    a = ap.parse_args()

    model = dwn_ref.load_model(a.model)
    if os.path.isdir(a.out) and os.listdir(a.out) and not a.force:
        sys.exit(f"{a.out} is not empty (files are never overwritten silently); use a new --out or --force")
    os.makedirs(a.out, exist_ok=True)
    v, info = emit_core(model, not a.no_reg_input, not a.no_reg_pop, not a.no_reg_argmax)
    with open(os.path.join(a.out, "dwn_core.v"), "w") as f:
        f.write(v)
    d = np.load(a.data)
    n_test = min(a.n_test, len(d["Xte"]))
    pred, _ = write_vectors(a.out, model, d["Xte"], d["yte"], n_test)
    info["n_test_vectors"] = n_test
    info["python_int_correct_on_vectors"] = int((pred == d["yte"][:n_test]).sum())
    with open(os.path.join(a.out, "dwn_params.vh"), "w") as f:
        f.write("// AUTO-GENERATED by dwn_to_verilog.py\n")
        f.write(f"localparam integer DWN_N_IN    = {info['n_in']};\n")
        f.write(f"localparam integer DWN_K       = {info['n_classes']};\n")
        f.write(f"localparam integer DWN_CW      = {info['count_width']};\n")
        f.write(f"localparam integer DWN_IW      = {info['pred_width']};\n")
        f.write(f"localparam integer DWN_LATENCY = {info['latency_cycles']};\n")
        f.write(f"localparam integer DWN_N_TEST  = {n_test};\n")
    with open(os.path.join(a.out, "tb_dwn_core.v"), "w") as f:
        f.write(TB)
    with open(os.path.join(a.out, "dwn_core_info.json"), "w") as f:
        json.dump(info, f, indent=2)
    print(json.dumps({k: info[k] for k in ("latency_cycles", "total_lut_nodes", "group_size",
                                          "count_width", "n_test_vectors")}))
    if a.sim:
        r = subprocess.run([a.iverilog, "-g2005", "-o", "tb.vvp", "-I", ".", "tb_dwn_core.v", "dwn_core.v"],
                           cwd=a.out, capture_output=True, text=True)
        if r.returncode:
            print(r.stdout, r.stderr)
            sys.exit("iverilog compile failed")
        r = subprocess.run([a.vvp, "-n", "tb.vvp"], cwd=a.out, capture_output=True, text=True)
        print(r.stdout.strip())
        with open(os.path.join(a.out, "sim_result.txt"), "w") as f:
            f.write(r.stdout)
        if "BIT-EXACT PASS" not in r.stdout:
            sys.exit(1)


if __name__ == "__main__":
    main()
